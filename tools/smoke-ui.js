const {_electron}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
(async()=>{
  const root=path.resolve(__dirname,'..');
  const packaged=process.argv.includes('--packaged');
  const single=process.argv.includes('--single-file');
  const app=await _electron.launch({cwd:root,executablePath:process.env.FRESHBOX_TEST_EXE||(single?path.join(root,`dist/FreshBox-Portable-${require('../package.json').version}.exe`):packaged?path.join(root,'dist/win-unpacked/FreshBox.exe'):require('electron')),args:packaged||single?[]:['.'],timeout:30000});
  const errors=[];
  try {
    const page=await app.firstWindow();
    page.on('pageerror',e=>errors.push(e.message));
    await page.locator('.app-card').first().waitFor();
    assert.equal(await page.locator('.app-card').count(),require('../reviewed-catalog').length);
    await page.locator('.app-icon').evaluateAll(images=>Promise.all(images.map(img=>{img.loading='eager';return img.decode()})));
    assert.equal(await page.locator('.app-icon').evaluateAll(images=>images.filter(img=>!img.complete||!img.naturalWidth||img.src.endsWith('/default.webp')).length),0);
    assert.equal(await page.locator('#selectedCount').textContent(),'0');
    await page.locator('#search').fill('Visual C++');
    assert.equal(await page.locator('.app-card').count(),2);
    await page.locator('#selectAll').click();
    assert.equal(await page.locator('#selectedCount').textContent(),'2');
    await page.locator('#clearAll').click();
    assert.equal(await page.locator('#selectedCount').textContent(),'0');
    await page.locator('#search').fill('WhatsApp');
    assert.equal(await page.locator('.app-card').count(),1);
    assert.equal(await page.locator('.app-card').getAttribute('data-id'),'9NKSQGP7F2NH');
    await page.locator('#search').fill('');
    await page.locator('#categorySelect').selectOption('پیش‌نیازها و Runtime');
    assert.equal(await page.locator('.app-card').count(),7);
    await page.locator('#languageSelect').selectOption('en');
    assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
    await page.locator('#languageSelect').selectOption('ru');
    assert.equal(await page.locator('#appsTitle').textContent(),'Выбор программ');
    await page.locator('#languageSelect').selectOption('fa');
    await page.locator('#installLocation').fill('D:\\Apps');
    await page.locator('#defaultLocation').click();
    assert.equal(await page.locator('#installLocation').inputValue(),'C:\\Program Files');
    await page.locator('#categorySelect').selectOption('all');
    await page.locator('#search').fill('Google Chrome');
    await page.locator('.app-card').click();
    await page.locator('#checkSources').click();
    await page.locator('#jobModalTitle').filter({hasText:'بررسی کامل شد'}).waitFor({timeout:90000});
    assert.match(await page.locator('#jobModalDetail').textContent(),/1 از 1/);
    await page.locator('#jobModalDone').click();
    await page.locator('#clearAll').click();
    await page.locator('#search').fill('');
    await page.evaluate(()=>window.scrollTo(0,0));
    fs.mkdirSync(path.join(root,'reports'),{recursive:true});
    await page.screenshot({path:path.join(root,'reports','ui-reviewed.png')});
    const result={packaged,cards:await page.locator('.app-card').count(),errors,overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)};
    fs.writeFileSync(path.join(root,'reports','ui-smoke.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
    assert.deepEqual(errors,[]);
  } finally {await app.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
